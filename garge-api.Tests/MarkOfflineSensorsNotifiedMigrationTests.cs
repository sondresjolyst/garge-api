using garge_api.Migrations;
using Npgsql;
using Xunit;

namespace garge_api.Tests;

/// <summary>
/// Runs the SQL of the MarkOfflineSensorsNotified migration on Postgres. Set GARGE_TEST_POSTGRES to a
/// connection string to run it. Each run works in a schema of its own and drops it afterwards.
/// </summary>
public class MarkOfflineSensorsNotifiedMigrationTests
{
    private static readonly string? ConnectionString = Environment.GetEnvironmentVariable("GARGE_TEST_POSTGRES");

    [Fact]
    public async Task Sql_MarksOnlyOfflineSensorsOfUsersWithAChannelAndNoOpenRow()
    {
        Assert.SkipWhen(string.IsNullOrEmpty(ConnectionString), "GARGE_TEST_POSTGRES is not set.");
        var ct = TestContext.Current.CancellationToken;
        var schema = "offline_" + Guid.NewGuid().ToString("N");
        await using var connection = new NpgsqlConnection(ConnectionString);
        await connection.OpenAsync(ct);
        await ExecuteAsync(connection, $"""
            CREATE SCHEMA {schema};
            SET search_path TO {schema};
            CREATE TABLE "UserProfiles" ("Id" text PRIMARY KEY, "EmailNotificationsEnabled" bool NOT NULL,
                "PushNotificationsEnabled" bool NOT NULL, "OfflineAlertThresholdHours" int NOT NULL);
            CREATE TABLE "UserSensors" ("UserId" text NOT NULL, "SensorId" int NOT NULL);
            CREATE TABLE "SensorData" ("Id" serial PRIMARY KEY, "SensorId" int NOT NULL, "Timestamp" timestamptz NOT NULL);
            CREATE TABLE "SensorOfflineNotifications" ("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "UserId" text NOT NULL, "SensorId" int NOT NULL, "Kind" varchar(16) NOT NULL,
                "NotifiedAt" timestamptz NOT NULL, "ResolvedAt" timestamptz);

            INSERT INTO "UserProfiles" VALUES ('email', true, false, 4), ('push', false, true, 4), ('none', false, false, 4);
            INSERT INTO "UserSensors" VALUES
                ('email', 1), ('email', 2), ('email', 3), ('email', 4), ('email', 5), ('email', 6),
                ('push', 1), ('none', 1);
            INSERT INTO "SensorData" ("SensorId", "Timestamp") VALUES
                (1, now() - interval '10 hours'),
                (2, now() - interval '1 hour'),
                (3, now() - interval '10 hours'),
                (4, now() - interval '10 hours'),
                (5, now() - interval '10 hours');
            INSERT INTO "SensorOfflineNotifications" ("UserId", "SensorId", "Kind", "NotifiedAt", "ResolvedAt") VALUES
                ('email', 3, 'offline', now() - interval '1 hour', NULL),
                ('email', 4, 'security', now() - interval '1 hour', NULL),
                ('email', 5, 'offline', now() - interval '9 hours', now() - interval '8 hours');
            """, ct);
        try
        {
            await ExecuteAsync(connection, MarkOfflineSensorsNotified.MarkOfflineNotifiedSql, ct);
            var rows = await RowsAsync(connection, ct);

            Assert.Single(rows, r => r is { User: "email", Sensor: 1, Kind: "offline", Resolved: false });
            Assert.Single(rows, r => r is { User: "push", Sensor: 1, Kind: "offline", Resolved: false });
            Assert.DoesNotContain(rows, r => r.User == "email" && r.Sensor == 2);
            Assert.Single(rows, r => r is { User: "email", Sensor: 3 });
            Assert.Single(rows, r => r is { User: "email", Sensor: 4 });
            Assert.Equal(2, rows.Count(r => r is { User: "email", Sensor: 5 }));
            Assert.Single(rows, r => r is { User: "email", Sensor: 6, Kind: "offline", Resolved: false });
            Assert.DoesNotContain(rows, r => r.User == "none");

            await ExecuteAsync(connection, MarkOfflineSensorsNotified.MarkOfflineNotifiedSql, ct);
            Assert.Equal(rows.Count, (await RowsAsync(connection, ct)).Count);
        }
        finally
        {
            await ExecuteAsync(connection, $"DROP SCHEMA {schema} CASCADE;", ct);
        }
    }

    private static async Task ExecuteAsync(NpgsqlConnection connection, string sql, CancellationToken ct)
    {
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync(ct);
    }

    private static async Task<List<(string User, int Sensor, string Kind, bool Resolved)>> RowsAsync(NpgsqlConnection connection, CancellationToken ct)
    {
        var rows = new List<(string, int, string, bool)>();
        await using var command = new NpgsqlCommand("""SELECT "UserId", "SensorId", "Kind", "ResolvedAt" IS NOT NULL FROM "SensorOfflineNotifications";""", connection);
        await using var reader = await command.ExecuteReaderAsync(ct);
        while (await reader.ReadAsync(ct))
            rows.Add((reader.GetString(0), reader.GetInt32(1), reader.GetString(2), reader.GetBoolean(3)));
        return rows;
    }
}
